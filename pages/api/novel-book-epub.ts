import type { NextApiRequest, NextApiResponse } from 'next';
import { BookSnapshotError, validateBookPdfRequest } from '../../shared/lib/novelBookSnapshot.mjs';
import { authenticateBookRequest, loadBookSnapshot } from '../../lib/novel-book/loadBookSnapshot.mjs';
import { renderBookEpub } from '../../lib/novel-book/renderBookEpub.mjs';

export const config = { api: { bodyParser: { sizeLimit: '16kb' }, responseLimit: false }, maxDuration: 300 };

type Dependencies = {
  authenticate?: typeof authenticateBookRequest;
  load?: typeof loadBookSnapshot;
  render?: typeof renderBookEpub;
  timeoutMs?: number;
};

function waitForDrain(res: NextApiResponse, signal: AbortSignal) {
  return new Promise<void>((resolve, reject) => {
    const cleanup = () => { res.off('drain', drained); signal.removeEventListener('abort', abort); };
    const drained = () => { cleanup(); resolve(); };
    const abort = () => { cleanup(); reject(new BookSnapshotError('BOOK_REQUEST_ABORTED', 504)); };
    res.once('drain', drained); signal.addEventListener('abort', abort, { once: true });
    if (signal.aborted) abort();
  });
}

/** Dependencies can be supplied by isolated tests, never by the HTTP request. */
export function createBookEpubHandler(dependencies: Dependencies = {}) {
  return async function handler(req: NextApiRequest, res: NextApiResponse) {
    res.setHeader('Cache-Control', 'private, no-store, max-age=0');
    res.setHeader('CDN-Cache-Control', 'no-store');
    res.setHeader('Vercel-CDN-Cache-Control', 'no-store');
    res.setHeader('Vary', 'Authorization');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    if (req.method !== 'POST') {
      res.setHeader('Allow', 'POST');
      return res.status(405).json({ error: 'METHOD_NOT_ALLOWED' });
    }
    const controller = new AbortController();
    let reader: ReadableStreamDefaultReader<Uint8Array> | undefined;
    let rendered: Awaited<ReturnType<typeof renderBookEpub>> | undefined;
    let timedOut = false;
    const disconnect = () => {
      if (!res.writableEnded) controller.abort();
    };
    const cancelReader = () => { void reader?.cancel().catch(() => {}); };
    req.once('aborted', disconnect);
    res.once('close', disconnect);
    controller.signal.addEventListener('abort', cancelReader);
    const timeout = setTimeout(() => { timedOut = true; controller.abort(); }, dependencies.timeoutMs ?? 270000);
    timeout.unref?.();
    try {
      const request = validateBookPdfRequest(req.body);
      const { client } = await (dependencies.authenticate || authenticateBookRequest)(req.headers.authorization,
        { signal: controller.signal });
      if (controller.signal.aborted) throw new BookSnapshotError('BOOK_REQUEST_ABORTED', 504);
      const snapshot = await (dependencies.load || loadBookSnapshot)(client, request.slug, { signal: controller.signal });
      if (controller.signal.aborted) throw new BookSnapshotError('BOOK_REQUEST_ABORTED', 504);
      rendered = await (dependencies.render || renderBookEpub)(snapshot, request.options, { signal: controller.signal });
      if (controller.signal.aborted) throw new BookSnapshotError('BOOK_REQUEST_ABORTED', 504);
      reader = rendered.stream.getReader();
      // The filename is generated by trusted code, but still guard header injection.
      const filename = /^[A-Za-z0-9][A-Za-z0-9._ -]{0,180}\.epub$/.test(rendered.filename)
        ? rendered.filename : `ROS-${snapshot.language}-book.epub`;
      res.setHeader('Content-Type', 'application/epub+zip');
      res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
      while (true) {
        const chunk = await reader.read();
        if (controller.signal.aborted) throw new BookSnapshotError('BOOK_REQUEST_ABORTED', 504);
        if (chunk.done) break;
        if (!res.write(Buffer.from(chunk.value))) await waitForDrain(res, controller.signal);
      }
      // Release renderer resources before completing the download.
      await rendered.close();
      rendered = undefined;
      res.end();
    } catch (error) {
      if (!(error instanceof BookSnapshotError)) console.error("EPUB export failure", error instanceof Error ? { name: error.name, frames: error.stack?.split("\n").slice(1, 4) } : {name: "Unknown"});
      if (res.destroyed) return;
      if (res.headersSent) { res.destroy(); return; }
      res.removeHeader('Content-Disposition');
      res.removeHeader('Content-Type');
      const known = error instanceof BookSnapshotError;
      const code = timedOut ? 'BOOK_REQUEST_TIMEOUT' : known ? error.code : 'BOOK_EPUB_FAILED';
      const status = timedOut ? 504 : known ? error.status : 500;
      res.status(status).json({ error: code });
    } finally {
      clearTimeout(timeout);
      req.off('aborted', disconnect); res.off('close', disconnect);
      controller.signal.removeEventListener('abort', cancelReader);
      try { await reader?.cancel(); } catch { /* connection already closed */ }
      try { reader?.releaseLock(); } catch { /* stream already released */ }
      try { await rendered?.close(); } catch { /* no token/content logging */ }
    }
  };
}

export default createBookEpubHandler();
