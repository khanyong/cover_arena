export function getParagraphText(
  paragraph: NovelParagraph,
  versionKey: string
): string {
  if (paragraph.versions[versionKey]) {
    return paragraph.versions[versionKey].content;
  }
  if (paragraph.versions[paragraph.activeVersion]) {
    return paragraph.versions[paragraph.activeVersion].content;
  }
  const keys = Object.keys(paragraph.versions);
  return keys.length > 0 ? paragraph.versions[keys[keys.length - 1]].content : "";
}

export function addParagraphVersion(
  novel: NovelDetails,
  paragraphId: string,
  newVersionKey: string,
  content: string,
  note?: string,
  author?: string
): NovelDetails {
  const updatedNovel: NovelDetails = JSON.parse(JSON.stringify(novel));

  for (const act of updatedNovel.acts) {
    for (const ch of act.chapters) {
      for (const p of ch.paragraphs) {
        if (p.id === paragraphId) {
          p.versions[newVersionKey] = {
            version: newVersionKey,
            content,
            note: note || "새 버전 업데이트",
            createdAt: new Date().toISOString().replace("T", " ").substring(0, 16),
            author: author || updatedNovel.author
          };
          p.activeVersion = newVersionKey;
        }
      }
    }
  }

  if (!updatedNovel.versionHistory.includes(newVersionKey)) {
    updatedNovel.versionHistory.push(newVersionKey);
    updatedNovel.versionHistory.sort();
  }

  updatedNovel.updatedAt = new Date().toISOString().substring(0, 10);
  return updatedNovel;
}

export function addParagraphAiComment(
  novel: NovelDetails,
  paragraphId: string,
  targetVersion: string,
  prompt: string
): NovelDetails {
  const updatedNovel: NovelDetails = JSON.parse(JSON.stringify(novel));

  for (const act of updatedNovel.acts) {
    for (const ch of act.chapters) {
      for (const p of ch.paragraphs) {
        if (p.id === paragraphId) {
          if (!p.aiPrompts) {
            p.aiPrompts = [];
            // Legacy 데이터 마이그레이션
            if (p.aiPrompt) {
              p.aiPrompts.push({
                id: crypto.randomUUID(),
                targetVersion: 'v1.0 (Legacy)',
                prompt: p.aiPrompt,
                createdAt: new Date().toISOString()
              });
            }
          }
          p.aiPrompts.push({
            id: crypto.randomUUID(),
            targetVersion,
            prompt,
            createdAt: new Date().toISOString()
          });
          p.aiPrompt = prompt; // 하위 호환성을 위해 최근 코멘트를 덮어씀
        }
      }
    }
  }

  return updatedNovel;
}

export function deleteParagraph(
  novel: NovelDetails,
  paragraphId: string
): NovelDetails {
  const updatedNovel: NovelDetails = JSON.parse(JSON.stringify(novel));

  for (const act of updatedNovel.acts) {
    for (const ch of act.chapters) {
      const initialLength = ch.paragraphs.length;
      ch.paragraphs = ch.paragraphs.filter(p => p.id !== paragraphId);
      if (ch.paragraphs.length !== initialLength) {
        // Found and removed
        updatedNovel.updatedAt = new Date().toISOString().substring(0, 10);
        return updatedNovel;
      }
    }
  }

  return updatedNovel;
}

