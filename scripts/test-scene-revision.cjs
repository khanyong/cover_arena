const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'components/NovelPlatform/sceneRevision.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const moduleExports = {};
new Function('exports', compiled.outputText)(moduleExports);
const { getSceneRevisionNumber } = moduleExports;
const publication = (edition) => ({ editorial_version: edition, approved_sha256: 'a'.repeat(64), applied_at: '2026-09-08T01:55:40Z' });
assert.equal(getSceneRevisionNumber({}), null);
assert.equal(getSceneRevisionNumber({ paragraphs: [{ activeVersion: 'v1' }] }), null);
assert.equal(getSceneRevisionNumber({ publication: publication('A0-CH2-SC2-RESTART-D3') }), 1);
assert.equal(getSceneRevisionNumber({ publication: { ...publication('D3'), approved_sha256: 'invalid' } }), null);
const original = { publication: publication('D3'), publicationHistory: [{ scene: { publication: publication('D1') } }, { scene: { publication: publication('D1') } }] };
const before = JSON.stringify(original);
assert.equal(getSceneRevisionNumber(original), 2);
assert.equal(JSON.stringify(original), before);
assert.equal(getSceneRevisionNumber({ publicationHistory: original.publicationHistory }), null);
const nested = { publication: publication('D4'), publicationHistory: [{ scene: original }] };
assert.equal(getSceneRevisionNumber(nested), 3);
const badgeSource = fs.readFileSync(path.join(root, 'components/NovelPlatform/SceneRevisionBadge.tsx'), 'utf8');
const badgeCompiled = ts.transpileModule(badgeSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.React, esModuleInterop: true } });
const badgeExports = {};
new Function('exports', 'require', badgeCompiled.outputText)(badgeExports, (id) => id === './sceneRevision' ? moduleExports : require(id));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
assert.equal(renderToStaticMarkup(React.createElement(badgeExports.SceneRevisionBadge, { scene: {} })), '');
const markup = renderToStaticMarkup(React.createElement(badgeExports.SceneRevisionBadge, { scene: { publication: publication('D3') } }));
assert.match(markup, /\[v1\]/);
assert.match(markup, /사용자 최종 검수 완료 표시는 아닙니다/);
const fixturePath = path.join(root, 'reports/scene-publication/A0-CH2-SC2-RESTART-D3/db-readback.json');
if (fs.existsSync(fixturePath)) {
  const scene = JSON.parse(fs.readFileSync(fixturePath, 'utf8')).verification.reader_scene;
  assert.equal(getSceneRevisionNumber(scene), 1);
  assert.equal(getSceneRevisionNumber(scene.publicationHistory[0].scene), null);
}
console.log('PASS: applied-edition badges, legacy exclusion, D3 => v1, deduplication, nested history, immutability');
